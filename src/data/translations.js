// Translate News Item dynamically helper
export function translateNews(item, lang) {
  if (!item) return null;
  if (lang === 'hi' && newsTranslations.hi[item.id]) {
    return {
      ...item,
      title: newsTranslations.hi[item.id].title || item.title,
      summary: newsTranslations.hi[item.id].summary || item.summary,
      content: newsTranslations.hi[item.id].content || item.content,
      category: uiTranslations.hi[item.category] || item.category
    };
  }
  return item;
}
